"""Промпт для GPT-фактів VIP-короткого дзвінка.

GPT повертає ТІЛЬКИ сирі факти. Жодних вердиктів — вердикт red/green/review
рахує core/vip_short_scoring.py. Статус бонусу QA обирає вручну (дропдаун),
GPT бонус більше не оцінює.
"""

VIP_SHORT_FACTS_SCHEMA = """
ФОРМАТ JSON:
{
  "facts": {
    "is_structured_call": bool,        // чи дзвінок мав звичну структуру (привітання, привід, бонус/умови, прощання)
    "answering_machine_detected": bool, // менеджер говорить, а на лінії немає живого клієнта, що
                                        // реально відповідає — з БУДЬ-ЯКОЇ технічної причини
                                        // (автовідповідач, клієнт поставив на утримання, обрив
                                        // зв'язку, тривала тиша без жодної реакції)
    "client_audio_missing_suspected": bool, // підозра, що репліки клієнта відсутні/не чутні через технічну проблему запису (не через дії менеджера)
    "is_birthday_greeting": bool,      // чи це привітання з Днем народження
    "rudeness_detected": bool,         // чи менеджер проявив грубість АБО дозволив хамство клієнту без реакції
    "rudeness_confidence": "low" | "medium" | "high",
    "objection_ignored": bool,         // заперечення клієнта проігноровано / опрацьовано формально
    "inaccurate_info_suspected": bool, // є підозра на недостовірну інформацію від менеджера
    "could_not_help_suspected": bool,  // клієнт мав вирішуване питання (депозит/виплата/бонус/технічна), яке не вирішили
    "missing_humanity_suspected": bool, // відсутня невимушеність/підтримка там, де вона була доречна
    "manager_fabricated_client_reason": bool, // менеджер "зливає" розмову: фабрикує відповідь/стан/причину
                                              // за клієнта замість реальної відповіді
    "comment_mismatch_detected": bool, // коментар QA (переданий нижче) НЕ відповідає тому, що реально
                                        // відбувалось у дзвінку (за змістом, не дослівно)
    "evidence": {
      // Для КОЖНОГО true-факта (і для is_structured_call=false) обов'язково заповни:
      // timing — час з транскрипту у форматі M:SS / MM:SS (маркер [M:SS] біля репліки),
      // quote — коротка цитата з діалогу (1–2 репліки), що підтверджує факт.
      // Якщо факт false — став null.
      "is_structured_call": {"timing": "0:12", "quote": "..."} | null,
      "answering_machine_detected": {"timing": "0:05", "quote": "..."} | null,
      "client_audio_missing_suspected": {"timing": "0:30", "quote": "..."} | null,
      "is_birthday_greeting": {"timing": "0:05", "quote": "..."} | null,
      "rudeness_detected": {"timing": "1:02", "quote": "..."} | null,
      "objection_ignored": {"timing": "0:48", "quote": "..."} | null,
      "inaccurate_info_suspected": {"timing": "1:10", "quote": "..."} | null,
      "could_not_help_suspected": {"timing": "0:55", "quote": "..."} | null,
      "missing_humanity_suspected": {"timing": "1:20", "quote": "..."} | null,
      "manager_fabricated_client_reason": {"timing": "0:30", "quote": "..."} | null,
      "comment_mismatch_detected": {"timing": "", "quote": "..."} | null
    }
  }
}
"""


def get_vip_short_analysis_prompt(qa_comment, important_note):
    return f"""
Ти аналізуєш короткий VIP-дзвінок (90-130 сек) кол-центру.
Поверни ONLY valid JSON за схемою нижче — без пояснень, без markdown.

{VIP_SHORT_FACTS_SCHEMA}

Словник скорочень, які використовує QA у коментарях (враховуй це при звірці
comment_mismatch_detected — це НЕ розбіжність, а власна термінологія команди):
- "4в1" — назва конкретного пакету бонусів (може не звучати цим словом у діалозі,
  менеджер описує його зміст своїми словами — наприклад "два бонуси в доступі").
- "бд" / "БД" / "бдб" — бездепозитний бонус. Менеджер НЕ може сказати "бездеп"
  напряму (заборонене формулювання) і замість цього вуалює: "бонус за активність",
  "бонус за активну гру", "амулет від менеджера" тощо — це те саме, що "бд" в коментарі,
  не розбіжність.
- Скорочені суми: "1к" = 1000, "300бдб" = 300 (бездеп бонус), і подібні — не вимагай
  дослівного числа з тим самим форматуванням.
- Якщо в діалозі згадано ту саму КІЛЬКІСТЬ бонусів і той самий приблизний зміст
  (напр. "два бонуси" в коментарі = "два в доступі" в діалозі) — це збіг, не mismatch,
  навіть якщо конкретні назви не прозвучали дослівно.

Правила:
- "rudeness_detected" став true тільки при явній грубості/маті — не за різкий тон.
- "manager_fabricated_client_reason" — це ключовий критерій "зливання" розмови. Став true, якщо помітиш
  БУДЬ-ЯКИЙ з цих патернів:
  1) Менеджер ставить клієнту питання (наприклад "зручно говорити?", "все добре?", "все нормально?")
     і, НЕ дочекавшись реальної відповіді клієнта в діалозі, сам відповідає за нього
     ("Радий це чути", "Все нормально. Супер") — і на цій сфабрикованій "відповіді" будує подальшу розмову.
  2) Менеджер прямо заявляє причину за клієнта, якої той не називав ("клієнту зараз незручно",
     "клієнт поспішає"), щоб швидше згорнути розмову.
  3) Менеджер отримує від клієнта реальну проблему/скаргу, дає їй мінімальну формальну відповідь
     ("зрозумів", "передам") і одразу різко перемикається на продажний пітч/бонус/завершення,
     не заглиблюючись у проблему клієнта.
  Якщо клієнт сам дійсно підтвердив те, що каже менеджер (є його репліка з підтвердженням) — це НЕ
  фабрикація, став false. Підтвердженням рахується БУДЬ-ЯКА репліка клієнта в діалозі перед
  твердженням менеджера — навіть одне слово ("Так", "Ага", "Поки ні", "Добре"). Довжина репліки
  не має значення, важлива сама її наявність. НЕ став true лише тому, що відповідь клієнта
  коротка чи неінформативна — короткість відповіді це не фабрикація.

  Приклади, які НЕ фабрикація (реальні кейси з тестування, де факт хибно спрацював):
  - "От зручно зараз. Так, так на хвилинку. Так. ... Радий це чути." — клієнт тричі відповів
    "так" перед реакцією менеджера.
  - "Поки ні. Поки ні. ...я би з вами поговорив, але спішу." — клієнт реально відповів,
    хай і коротко й із поясненням поспіху.

  НЕ рахується фабрикацією (став false): менеджер уточнює/перефразовує зі словами-маркерами
  розуміння ("наскільки я розумію", "як я зрозумів", "правильно?") — це перевірка розуміння,
  а не твердження замість клієнта. Приклад, який НЕ є фабрикацією:
  "Ви сьогодні будете грати, наскільки я розумію. Добре." — тут "наскільки я розумію" прямо
  показує, що менеджер уточнює, а не стверджує за клієнта.
- Для *_suspected полів став true лише при очевидних ознаках у транскрипті, не додумуй.
- "missing_humanity_suspected": став true, ЯКЩО клієнт явно потребував емоційної підтримки чи
  простого людського відгуку (згадав хворобу, втрату, складну життєву ситуацію, службу тощо),
  а менеджер ПРОІГНОРУВАВ це і одразу перейшов до продажного питання/бонусу без жодної реакції.

  НЕ рахується (став false): менеджер відреагував БУДЬ-ЯКИМИ словами підтримки/співчуття/
  побажання, навіть коротко — "одужуйте", "тримайтесь", "співчуваю", "я вас почула", "бережіть
  себе" — це і Є прояв людяності, а не її відсутність.

  ОБОВ'ЯЗКОВА самоперевірка перед тим, як ставити true: прочитай цитату, яку сам збираєшся
  навести як evidence. Якщо в цій цитаті менеджер каже щось тепле/підтримуюче — це ДОКАЗ
  ПРОТИ факту, не за нього. У такому разі постав false, а не true. Приклад помилки, якої
  НЕ РОБИ: цитата "Я вас почула. Дійсно, одужуйте обов'язково. Я з вами на зв'язку буду." —
  тут явно Є підтримка, тому missing_humanity_suspected = false, а не true.
- "answering_machine_detected": став true, якщо менеджер говорить, а насправді на лінії немає
  живого клієнта, що реально реагує на його слова — незалежно від ТЕХНІЧНОЇ причини. Це
  ШИРОКА категорія, рахуй БУДЬ-ЯКЕ з цього:
  1) Автовідповідач/голосова пошта: "переадресовується на автовідповідач", "залиште
     повідомлення після сигналу", стандартні автоматичні фрази оператора.
  2) Клієнт поставив виклик на утримання (hold): менеджер прямо каже про це
     ("ви поставили на утримання", "спробуйте відключити утримання", "я вас чекаю на лінії").
  3) Обрив зв'язку чи тривала тиша: після певного моменту клієнт повністю перестає
     відповідати, а менеджер продовжує говорити сам, багаторазово перепитуючи
     ("Сергію?", "Ви мене чуєте?") без жодної відповіді.
  4) Репліки, підписані як клієнт, звучать беззмістовно/уривчасто і не є реальними
     відповідями на слова менеджера.

  Якщо цей факт true — ІГНОРУЙ решту поведінкових фактів (manager_fabricated_client_reason,
  objection_ignored, could_not_help_suspected, missing_humanity_suspected, rudeness_detected)
  для цього дзвінка, постав їх усі false — оцінювати поведінку менеджера в розмові, де немає
  живого співрозмовника, безглуздо.

  Приклад (реальний кейс, де попередня вужча версія факту не спрацювала): менеджер каже
  "Хвилинку маєте. О, так шкода." одразу після привітання, далі кілька разів перепитує
  ("Сергію?"), а потім прямо каже "Сергію, ви поставили на утримання. Спробуйте відключити
  утримання? Я вас наберу ще раз." — це answering_machine_detected=true (клієнт на утриманні),
  а НЕ фабрикація чи ігнор заперечення.
- "client_audio_missing_suspected": став true, якщо після певного моменту в діалозі повністю
  зникають репліки клієнта, а менеджер продовжує говорити один — і це схоже на технічну
  проблему запису/каналу, а не на реальний монолог менеджера. Це НЕ впливає на is_structured_call —
  оцінюй структуру лише за тим, що сказав менеджер.
- "comment_mismatch_detected": ЗА ЗАМОВЧУВАННЯМ false. Це найсуворіший факт у всій схемі —
  тестування показало систематичне перегинання (6 з 7 спрацювань у тестовій вибірці виявились
  хибними). Став true ТІЛЬКИ якщо коментар містить ПРЯМЕ, ОДНОЗНАЧНЕ твердження, яке діалог
  ЯВНО СПРОСТОВУЄ — не "не згадано", а саме "сказано протилежне". Приклад справжнього mismatch:
  коментар каже "бонус залишено", а менеджер в діалозі прямо каже "на жаль, зараз бонусів
  немає". Якщо є БУДЬ-ЯКИЙ спосіб прочитати коментар так, щоб він узгоджувався з діалогом
  (інша транслітерація того самого слова, скорочення, часткова інформація, стислий переказ) —
  це НЕ mismatch, став false. Сумніваєшся — став false.

  Короткий формат коментаря — стандарт для цих дзвінків, не недолік: достатньо суми і типу
  бонусу, розгорнутий опис не потрібен.

  Приклади, які НЕ mismatch (реальні кейси з тестування, де факт хибно спрацював):
  - Коментар "лутбокс" / "лотбокс" — різна транслітерація того самого слова, не розбіжність.
  - Коментар називає суму й умови бонусу (вейджер, x5 тощо), і в діалозі звучать ТІ САМІ числа —
    навіть якщо порядок слів чи формулювання різні, це збіг, не mismatch.
  - Клієнт каже "Не те, що не зручно, я на позиції зараз" (ЗСУ) — коментар, що згадує позицію/
    службу, ВІДПОВІДАЄ дійсності, не mismatch.
  - Клієнта виселяють з житла, менеджер про це чує і адаптує пропозицію — коментар, що це
    відображає, ВІДПОВІДАЄ дійсності.
  - "2 ЗВ. ВСЕ ОК, ВОПРОСОВ нет. ОСТ 4в1 +300бдб"
  - "2 ЗВ. все ок, попросил возоб, акт и деакт сразу бд 1000бд"
  - "Другий // бонус 4в1 і бд 3к х 25 на сайті все ок"
- Репліки в транскрипті мають маркери часу у форматі "Спікер: [M:SS] текст" або "ch_0: [M:SS] текст".
  Бери timing ТІЛЬКИ з цих маркерів. Не вигадуй час.
- Якщо факт true (або is_structured_call=false) — evidence для нього ОБОВ'ЯЗКОВИЙ: і timing, і quote.
  Quote має бути реальною цитатою / коротким фрагментом з транскрипту.

КОНТЕКСТ ВІД QA:
Важливе: {important_note or "—"}
Коментар по дзвінку: {qa_comment or "—"}
"""
